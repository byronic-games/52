(function () {
  const body = document.getElementById("text-table-body");
  const search = document.getElementById("text-search");
  const locale = document.getElementById("locale-code");
  const summary = document.getElementById("text-summary");
  const errors = document.getElementById("text-errors");
  if (!body || typeof TEXT_CATALOG !== "object") return;

  const initialOverrides = typeof TEXT_CATALOG_OVERRIDES === "object" ? { ...TEXT_CATALOG_OVERRIDES } : {};
  let edits = { ...initialOverrides };
  locale.value = typeof TEXT_CATALOG_LOCALE === "string" ? TEXT_CATALOG_LOCALE : "en-GB";

  function escapeHtml(value) {
    return String(value ?? "").replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;").replace(/'/g,"&#039;");
  }

  function placeholders(value) {
    return [...new Set([...String(value || "").matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((match) => match[1]))].sort();
  }

  function missingPlaceholders(key) {
    const override = edits[key];
    if (!override) return [];
    const translated = new Set(placeholders(override));
    return placeholders(TEXT_CATALOG[key].text).filter((name) => !translated.has(name));
  }

  function visibleEntries() {
    const query = search.value.trim().toLowerCase();
    return Object.entries(TEXT_CATALOG).filter(([key, entry]) => !query || `${key} ${entry.category} ${entry.text} ${edits[key] || ""}`.toLowerCase().includes(query));
  }

  function render() {
    const entries = visibleEntries();
    body.innerHTML = entries.map(([key, entry]) => {
      const vars = placeholders(entry.text);
      const missing = missingPlaceholders(key);
      return `<tr>
        <td class="text-key">${escapeHtml(key)}</td>
        <td class="category">${escapeHtml(entry.category)}</td>
        <td class="default-copy">${escapeHtml(entry.text)}</td>
        <td><textarea class="translation-field${missing.length ? " invalid" : ""}" data-key="${escapeHtml(key)}" placeholder="Use default English">${escapeHtml(edits[key] || "")}</textarea></td>
        <td class="placeholder-list">${vars.length ? vars.map((name) => `{${escapeHtml(name)}}`).join(" ") : "-"}</td>
      </tr>`;
    }).join("");
    const edited = Object.values(edits).filter((value) => String(value).trim()).length;
    const invalid = Object.keys(edits).filter((key) => missingPlaceholders(key).length).length;
    summary.textContent = `Showing ${entries.length} of ${Object.keys(TEXT_CATALOG).length} strings. ${edited} override${edited === 1 ? "" : "s"}.`;
    errors.textContent = invalid ? `${invalid} translation${invalid === 1 ? " is" : "s are"} missing required placeholders.` : "";
  }

  function serialize() {
    const clean = Object.fromEntries(Object.entries(edits).filter(([, value]) => String(value).trim()));
    return `/* Generated by text-index.html. Edit there, then replace this file. */\nconst TEXT_CATALOG_LOCALE = ${JSON.stringify(locale.value.trim() || "en-GB")};\nconst TEXT_CATALOG_OVERRIDES = ${JSON.stringify(clean, null, 2)};\n`;
  }

  function download() {
    const invalidKeys = Object.keys(edits).filter((key) => missingPlaceholders(key).length);
    if (invalidKeys.length) {
      errors.textContent = `Fix missing placeholders before export: ${invalidKeys.join(", ")}`;
      return;
    }
    const blob = new Blob([serialize()], { type:"text/javascript;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "text-catalog-overrides.js";
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
  }

  body.addEventListener("input", (event) => {
    if (!event.target.matches(".translation-field")) return;
    edits[event.target.dataset.key] = event.target.value;
    const missing = missingPlaceholders(event.target.dataset.key);
    event.target.classList.toggle("invalid", missing.length > 0);
    const edited = Object.values(edits).filter((value) => String(value).trim()).length;
    summary.textContent = `Showing ${visibleEntries().length} of ${Object.keys(TEXT_CATALOG).length} strings. ${edited} override${edited === 1 ? "" : "s"}.`;
    errors.textContent = Object.keys(edits).some((key) => missingPlaceholders(key).length) ? "One or more translations are missing required placeholders." : "";
  });
  search.addEventListener("input", render);
  document.getElementById("download-text-btn").addEventListener("click", download);
  document.getElementById("reset-text-btn").addEventListener("click", () => { edits = { ...initialOverrides }; render(); });
  render();
})();
