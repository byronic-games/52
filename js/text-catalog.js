function getText(key, variables = {}) {
  const fallback = TEXT_CATALOG[key]?.text ?? key;
  const override = typeof TEXT_CATALOG_OVERRIDES !== "undefined" ? TEXT_CATALOG_OVERRIDES[key] : "";
  const template = typeof override === "string" && override.trim() ? override : fallback;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
  ));
}
