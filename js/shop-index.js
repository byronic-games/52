(function () {
  const tableBody = document.getElementById("card-back-table-body");
  const summaryEl = document.getElementById("catalog-summary");
  const downloadCatalogBtn = document.getElementById("download-catalog-btn");
  const resetCatalogBtn = document.getElementById("reset-catalog-btn");
  const addCardBackBtn = document.getElementById("add-card-back-btn");
  if (!tableBody || !Array.isArray(CARD_BACK_COSMETICS)) return;

  const originalCatalog = CARD_BACK_COSMETICS.map((item) => ({ ...item }));
  let editableCatalog = originalCatalog.map((item) => ({ ...item }));

  function escapeHtml(value) {
    return String(value ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }

  function field(item, key, type = "text") {
    return `<input class="catalog-field" data-id="${escapeHtml(item.id)}" data-field="${key}" type="${type}" value="${escapeHtml(item[key] ?? "")}"${type === "number" ? ' min="0" step="1"' : ""}>`;
  }

  function getPreviewStyle(item) {
    if (item.image) return `background-image:url('${String(item.image).replace(/'/g, "%27")}')`;
    const fallback = {
      classic: "images/LargeCards/back01.png",
      midnight_stars: "images/LargeCards/back06.png",
      neon_table: "images/LargeCards/back07.png",
      royal_felt: "images/LargeCards/back03.png",
    }[item.id] || "images/LargeCards/back01.png";
    return `background-image:url('${fallback}')`;
  }

  function row(item) {
    return `<tr>
      <td><div class="back-preview" style="${getPreviewStyle(item)}" aria-hidden="true"></div></td>
      <td>${field(item, "id")}</td>
      <td>${field(item, "name")}</td>
      <td><textarea class="catalog-field" data-id="${escapeHtml(item.id)}" data-field="description">${escapeHtml(item.description)}</textarea></td>
      <td class="checkbox-cell"><input data-id="${escapeHtml(item.id)}" data-field="included" type="checkbox" ${item.included !== false ? "checked" : ""} aria-label="${escapeHtml(item.name)} available"></td>
      <td>${field(item, "cost", "number")}</td>
      <td class="checkbox-cell"><input data-id="${escapeHtml(item.id)}" data-field="hiddenWhenUnowned" type="checkbox" ${item.hiddenWhenUnowned ? "checked" : ""} aria-label="${escapeHtml(item.name)} hidden until owned"></td>
      <td>${field(item, "image")}</td>
    </tr>`;
  }

  function render() {
    tableBody.innerHTML = editableCatalog.map(row).join("");
    const available = editableCatalog.filter((item) => item.included !== false).length;
    summaryEl.textContent = `${available} of ${editableCatalog.length} card backs available in the shop.`;
  }

  function updateField(target) {
    const item = editableCatalog.find((entry) => entry.id === target.dataset.id);
    if (!item) return;
    const key = target.dataset.field;
    if (key === "id") {
      const nextId = String(target.value || "").trim().replace(/[^a-z0-9_-]+/gi, "_").toLowerCase();
      if (!nextId || editableCatalog.some((entry) => entry !== item && entry.id === nextId)) return;
      item.id = nextId;
      target.closest("tr")?.querySelectorAll("[data-id]").forEach((fieldEl) => { fieldEl.dataset.id = nextId; });
      return;
    }
    if (target.type === "checkbox") item[key] = target.checked;
    else if (target.type === "number") item[key] = Math.max(0, Number.parseInt(target.value, 10) || 0);
    else item[key] = target.value;
    if (key === "included") render();
    else if (key === "image") {
      const preview = target.closest("tr")?.querySelector(".back-preview");
      if (preview) preview.style.backgroundImage = `url('${String(item.image || "images/LargeCards/back01.png").replace(/'/g, "%27")}')`;
    }
    else summaryEl.textContent = `${editableCatalog.filter((entry) => entry.included !== false).length} of ${editableCatalog.length} card backs available in the shop.`;
  }

  function serializeCatalog() {
    const lines = editableCatalog.map((item) => {
      const data = {
        name: item.name,
        description: item.description,
        cost: Math.max(0, Number(item.cost) || 0),
        included: item.included !== false,
        hiddenWhenUnowned: !!item.hiddenWhenUnowned,
      };
      if (item.image) data.image = item.image;
      return `  ${JSON.stringify(item.id)}: ${JSON.stringify(data)},`;
    });
    return `/* Generated by shop-index.html. Edit there, then replace this file. */\nconst CARD_BACK_CATALOG_OVERRIDES = {\n${lines.join("\n")}\n};\n`;
  }

  function downloadBlob(blob, filename) {
    const link = document.createElement("a");
    const url = URL.createObjectURL(blob);
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
  }

  tableBody.addEventListener("input", (event) => {
    if (event.target?.dataset?.field) updateField(event.target);
  });
  tableBody.addEventListener("change", (event) => {
    if (event.target?.dataset?.field) updateField(event.target);
  });
  downloadCatalogBtn.addEventListener("click", () => {
    downloadBlob(new Blob([serializeCatalog()], { type: "text/javascript;charset=utf-8" }), "card-back-catalog-overrides.js");
  });
  resetCatalogBtn.addEventListener("click", () => {
    editableCatalog = originalCatalog.map((item) => ({ ...item }));
    render();
  });
  addCardBackBtn.addEventListener("click", () => {
    let suffix = editableCatalog.length + 1;
    while (editableCatalog.some((item) => item.id === `new_card_back_${suffix}`)) suffix += 1;
    editableCatalog.push({
      id: `new_card_back_${suffix}`,
      name: "New Card Back",
      description: "",
      cost: 100,
      included: true,
      hiddenWhenUnowned: false,
      image: `images/card_backs/new_card_back_${suffix}.png`,
    });
    render();
    tableBody.lastElementChild?.scrollIntoView({ behavior: "smooth", block: "center" });
    tableBody.lastElementChild?.querySelector('[data-field="name"]')?.focus();
  });
  render();

  const canvas = document.getElementById("artwork-canvas");
  const context = canvas?.getContext("2d");
  const fileInput = document.getElementById("artwork-file");
  const nameInput = document.getElementById("artwork-name");
  const fitInput = document.getElementById("artwork-fit");
  const frameColorInput = document.getElementById("frame-color");
  const artworkColorInput = document.getElementById("artwork-color");
  const guidesInput = document.getElementById("show-guides");
  const statusEl = document.getElementById("artwork-status");
  let sourceImage = null;

  function roundedRect(ctx, x, y, width, height, radius) {
    ctx.beginPath();
    ctx.roundRect(x, y, width, height, radius);
  }

  function drawImageFit(ctx, image, x, y, width, height, fit) {
    if (fit === "stretch") {
      ctx.drawImage(image, x, y, width, height);
      return;
    }
    const scale = fit === "contain"
      ? Math.min(width / image.naturalWidth, height / image.naturalHeight)
      : Math.max(width / image.naturalWidth, height / image.naturalHeight);
    const drawWidth = image.naturalWidth * scale;
    const drawHeight = image.naturalHeight * scale;
    ctx.drawImage(image, x + (width - drawWidth) / 2, y + (height - drawHeight) / 2, drawWidth, drawHeight);
  }

  function paintCard(ctx, width, height, includeGuides = false) {
    const scale = width / 352;
    const frame = 12 * scale;
    ctx.clearRect(0, 0, width, height);
    roundedRect(ctx, 0, 0, width, height, 22 * scale);
    ctx.fillStyle = frameColorInput.value;
    ctx.fill();
    ctx.save();
    roundedRect(ctx, frame, frame, width - frame * 2, height - frame * 2, 15 * scale);
    ctx.clip();
    ctx.fillStyle = artworkColorInput.value;
    ctx.fillRect(frame, frame, width - frame * 2, height - frame * 2);
    if (sourceImage) drawImageFit(ctx, sourceImage, frame, frame, width - frame * 2, height - frame * 2, fitInput.value);
    ctx.restore();
    if (includeGuides) {
      ctx.save();
      ctx.setLineDash([8 * scale, 6 * scale]);
      ctx.lineWidth = Math.max(1, 2 * scale);
      ctx.strokeStyle = "rgba(255,255,255,0.9)";
      roundedRect(ctx, 24 * scale, 24 * scale, width - 48 * scale, height - 48 * scale, 10 * scale);
      ctx.stroke();
      ctx.restore();
    }
  }

  function renderArtwork() {
    if (!context) return;
    paintCard(context, canvas.width, canvas.height, guidesInput.checked);
  }

  function safeFilename() {
    return String(nameInput.value || "new_card_back").trim().replace(/[^a-z0-9_-]+/gi, "_").replace(/^_+|_+$/g, "") || "new_card_back";
  }

  function exportArtwork(width, height, suffix) {
    const output = document.createElement("canvas");
    output.width = width;
    output.height = height;
    paintCard(output.getContext("2d"), width, height, false);
    output.toBlob((blob) => {
      if (!blob) return;
      downloadBlob(blob, `${safeFilename()}_${suffix}.png`);
      statusEl.textContent = `Exported ${width} x ${height} PNG.`;
    }, "image/png");
  }

  fileInput.addEventListener("change", () => {
    const file = fileInput.files?.[0];
    if (!file) return;
    const image = new Image();
    const url = URL.createObjectURL(file);
    image.onload = () => {
      sourceImage = image;
      if (nameInput.value === "new_card_back") nameInput.value = file.name.replace(/\.[^.]+$/, "");
      URL.revokeObjectURL(url);
      renderArtwork();
      statusEl.textContent = `${file.name} loaded.`;
    };
    image.src = url;
  });
  [fitInput, frameColorInput, artworkColorInput, guidesInput].forEach((control) => control.addEventListener("input", renderArtwork));
  document.getElementById("export-large-btn").addEventListener("click", () => exportArtwork(352, 512, "large"));
  document.getElementById("export-small-btn").addEventListener("click", () => exportArtwork(66, 96, "small"));
  document.getElementById("download-template-btn").addEventListener("click", () => {
    const previousImage = sourceImage;
    sourceImage = null;
    exportArtwork(352, 512, "template");
    sourceImage = previousImage;
    renderArtwork();
  });
  renderArtwork();
})();
